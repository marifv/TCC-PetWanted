BEGIN;

CREATE TABLE IF NOT EXISTS preferencias_conversa (
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    conversa_id INTEGER NOT NULL REFERENCES conversas(id) ON DELETE CASCADE,
    silenciada_em TIMESTAMPTZ,
    excluida_em TIMESTAMPTZ,
    PRIMARY KEY (usuario_id, conversa_id)
);

CREATE TABLE IF NOT EXISTS denuncias_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id INTEGER NOT NULL REFERENCES conversas(id) ON DELETE CASCADE,
    denunciante_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    denunciado_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    motivo VARCHAR(500) NOT NULL,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (conversa_id, denunciante_id),
    CONSTRAINT denuncias_chat_participantes_distintos CHECK (denunciante_id <> denunciado_id)
);

COMMIT;