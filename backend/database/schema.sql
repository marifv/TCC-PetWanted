-- Execute this script once in a new, empty PostgreSQL database.
BEGIN;

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    documento VARCHAR(14) NOT NULL UNIQUE,
    senha VARCHAR(255),
    localizacao VARCHAR(150),
    tipo_perfil VARCHAR(20) NOT NULL CHECK (tipo_perfil IN ('Tutor', 'ONG')),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    foto TEXT,
    google_sub TEXT UNIQUE
);

CREATE UNIQUE INDEX IF NOT EXISTS usuarios_email_lower_unique
    ON usuarios (LOWER(email));

CREATE TABLE IF NOT EXISTS animais (
    id_animal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100),
    especie VARCHAR(100) NOT NULL,
    raca VARCHAR(100) NOT NULL,
    cor VARCHAR(100) NOT NULL,
    porte VARCHAR(100) NOT NULL,
    sexo VARCHAR(100) NOT NULL,
    local_desaparecimento VARCHAR(100) NOT NULL DEFAULT '',
    local_encontrado VARCHAR(100) NOT NULL DEFAULT '',
    data_evento DATE NOT NULL,
    tipo_registro VARCHAR(100) NOT NULL CHECK (tipo_registro IN ('Perdido', 'Encontrado', 'Adocao')),
    descricao VARCHAR(255),
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    status VARCHAR(100),
    idade VARCHAR(20),
    faixa_etaria VARCHAR(100),
    local_latitude DOUBLE PRECISION,
    local_longitude DOUBLE PRECISION,
    foto TEXT,
    fotos JSONB NOT NULL DEFAULT '[]'::jsonb
);

CREATE INDEX IF NOT EXISTS animais_id_usuario_idx
    ON animais (id_usuario);
CREATE INDEX IF NOT EXISTS animais_tipo_registro_idx
    ON animais (tipo_registro);

CREATE TABLE IF NOT EXISTS password_reset_requests (
    email TEXT PRIMARY KEY,
    code_hash CHAR(64),
    code_expires_at TIMESTAMPTZ,
    code_attempts INTEGER NOT NULL DEFAULT 0 CHECK (code_attempts >= 0),
    last_sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reset_token_hash CHAR(64),
    reset_token_expires_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS conversas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_1_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    usuario_2_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    animal_id INTEGER REFERENCES animais(id_animal) ON DELETE SET NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT conversas_usuarios_distintos CHECK (usuario_1_id <> usuario_2_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS conversas_participantes_animal_unique
    ON conversas (usuario_1_id, usuario_2_id, (COALESCE(animal_id, 0)));

CREATE TABLE IF NOT EXISTS mensagens_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id INTEGER NOT NULL REFERENCES conversas(id) ON DELETE CASCADE,
    remetente_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    conteudo TEXT NOT NULL CHECK (char_length(conteudo) BETWEEN 1 AND 2000),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    lida_em TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS mensagens_chat_conversa_criada_idx
    ON mensagens_chat (conversa_id, criado_em, id);

CREATE TABLE IF NOT EXISTS chat_dispositivos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token TEXT NOT NULL UNIQUE,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS preferencias_conversa (
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    conversa_id INTEGER NOT NULL REFERENCES conversas(id) ON DELETE CASCADE,
    silenciada_em TIMESTAMPTZ,
    excluida_em TIMESTAMPTZ,
    PRIMARY KEY (usuario_id, conversa_id)
);

CREATE TABLE IF NOT EXISTS denuncias_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id INTEGER NOT NULL REFERENCES conversas(id) ON DELETE CASCADE,
    denunciante_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    denunciado_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    motivo VARCHAR(500) NOT NULL,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (conversa_id, denunciante_id),
    CONSTRAINT denuncias_chat_participantes_distintos CHECK (denunciante_id <> denunciado_id)
);

COMMIT;
