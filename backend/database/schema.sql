-- Schema completo do PetWanted.
-- Seguro para novos bancos e para atualizar bancos existentes.
BEGIN;

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    documento VARCHAR(14) NOT NULL UNIQUE,
    senha VARCHAR(255),
    localizacao VARCHAR(150),
    tipo_perfil VARCHAR(20) NOT NULL CHECK (tipo_perfil IN ('Tutor', 'ONG')),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    foto TEXT,
    google_sub TEXT UNIQUE
);

CREATE UNIQUE INDEX IF NOT EXISTS usuarios_email_lower_unique
    ON usuarios (LOWER(email));

CREATE TABLE IF NOT EXISTS usuarios_atividade_diaria (
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    dia DATE NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (usuario_id, dia)
);

CREATE INDEX IF NOT EXISTS usuarios_atividade_diaria_dia_idx
    ON usuarios_atividade_diaria (dia);

CREATE TABLE IF NOT EXISTS admin_accounts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('owner', 'analyst')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ultimo_login_em TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS admin_accounts_email_lower_unique
    ON admin_accounts (LOWER(email));

CREATE TABLE IF NOT EXISTS admin_invites (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('owner', 'analyst')),
    token_hash CHAR(64) NOT NULL UNIQUE,
    convidado_por INTEGER NOT NULL REFERENCES admin_accounts(id),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expira_em TIMESTAMPTZ NOT NULL,
    aceito_em TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS admin_invites_email_idx
    ON admin_invites (LOWER(email), expira_em)
    WHERE aceito_em IS NULL;

CREATE TABLE IF NOT EXISTS admin_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id INTEGER REFERENCES admin_accounts(id) ON DELETE SET NULL,
    acao VARCHAR(50) NOT NULL,
    email_alvo VARCHAR(254),
    detalhes JSONB NOT NULL DEFAULT '{}'::jsonb,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE usuarios DROP COLUMN IF EXISTS telefone;

CREATE TABLE IF NOT EXISTS animais (
    id_animal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100),
    especie VARCHAR(100) NOT NULL,
    raca VARCHAR(100) NOT NULL,
    cor VARCHAR(100) NOT NULL,
    porte VARCHAR(100) NOT NULL,
    sexo VARCHAR(100) NOT NULL,
    local_desaparecimento VARCHAR(100) NOT NULL DEFAULT '',
    local_encontrado VARCHAR(100) NOT NULL DEFAULT '',
    data_evento DATE NOT NULL,
    tipo_registro VARCHAR(100) NOT NULL CHECK (tipo_registro IN ('Perdido', 'Encontrado', 'Adocao')),
    descricao VARCHAR(255),
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    status VARCHAR(100),
    idade VARCHAR(20),
    faixa_etaria VARCHAR(100),
    local_latitude DOUBLE PRECISION,
    local_longitude DOUBLE PRECISION,
    foto TEXT,
    fotos JSONB NOT NULL DEFAULT '[]'::jsonb
);

ALTER TABLE animais DROP COLUMN IF EXISTS responsavel;
ALTER TABLE animais DROP COLUMN IF EXISTS contato;

UPDATE animais
SET fotos = jsonb_build_array(foto)
WHERE foto IS NOT NULL AND fotos = '[]'::jsonb;

CREATE INDEX IF NOT EXISTS animais_id_usuario_idx ON animais (id_usuario);
CREATE INDEX IF NOT EXISTS animais_tipo_registro_idx ON animais (tipo_registro);

CREATE TABLE IF NOT EXISTS password_reset_requests (
    email TEXT PRIMARY KEY,
    code_hash CHAR(64),
    code_expires_at TIMESTAMPTZ,
    code_attempts INTEGER NOT NULL DEFAULT 0 CHECK (code_attempts >= 0),
    last_sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reset_token_hash CHAR(64),
    reset_token_expires_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS conversas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_1_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    usuario_2_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    animal_id INTEGER REFERENCES animais(id_animal) ON DELETE SET NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT conversas_usuarios_distintos CHECK (usuario_1_id <> usuario_2_id)
);

ALTER TABLE conversas ADD COLUMN IF NOT EXISTS animal_id INTEGER REFERENCES animais(id_animal) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS mensagens_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id INTEGER NOT NULL REFERENCES conversas(id) ON DELETE CASCADE,
    remetente_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    conteudo TEXT NOT NULL CHECK (char_length(conteudo) BETWEEN 1 AND 2000),
    animal_id INTEGER REFERENCES animais(id_animal) ON DELETE SET NULL,
    anexo_url TEXT,
    anexo_tipo VARCHAR(20),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    lida_em TIMESTAMPTZ
);

ALTER TABLE mensagens_chat ADD COLUMN IF NOT EXISTS animal_id INTEGER REFERENCES animais(id_animal) ON DELETE SET NULL;
ALTER TABLE mensagens_chat ADD COLUMN IF NOT EXISTS anexo_url TEXT;
ALTER TABLE mensagens_chat ADD COLUMN IF NOT EXISTS anexo_tipo VARCHAR(20);
ALTER TABLE mensagens_chat ADD COLUMN IF NOT EXISTS lida_em TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS mensagens_chat_conversa_criada_idx
    ON mensagens_chat (conversa_id, criado_em, id);

CREATE TABLE IF NOT EXISTS chat_dispositivos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token TEXT NOT NULL UNIQUE,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS preferencias_conversa (
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    conversa_id INTEGER NOT NULL REFERENCES conversas(id) ON DELETE CASCADE,
    silenciada_em TIMESTAMPTZ,
    excluida_em TIMESTAMPTZ,
    PRIMARY KEY (usuario_id, conversa_id)
);

CREATE TABLE IF NOT EXISTS denuncias_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id INTEGER NOT NULL REFERENCES conversas(id) ON DELETE CASCADE,
    denunciante_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    denunciado_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    motivo VARCHAR(500) NOT NULL,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (conversa_id, denunciante_id),
    CONSTRAINT denuncias_chat_participantes_distintos CHECK (denunciante_id <> denunciado_id)
);

CREATE TABLE IF NOT EXISTS analises_ia_animais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anuncio_id INTEGER NOT NULL REFERENCES animais(id_animal) ON DELETE CASCADE,
    modelo VARCHAR(100) NOT NULL,
    resultado_json JSONB NOT NULL,
    confianca NUMERIC(5,4),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS analises_ia_animais_anuncio_unique
    ON analises_ia_animais(anuncio_id);

CREATE TABLE IF NOT EXISTS matches_animais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anuncio_perdido_id INTEGER NOT NULL REFERENCES animais(id_animal) ON DELETE CASCADE,
    anuncio_encontrado_id INTEGER NOT NULL REFERENCES animais(id_animal) ON DELETE CASCADE,
    score_total NUMERIC(5,2) NOT NULL,
    score_visual NUMERIC(5,2),
    score_descricao NUMERIC(5,2),
    score_localizacao NUMERIC(5,2),
    score_tempo NUMERIC(5,2),
    status VARCHAR(30) NOT NULL DEFAULT 'pendente',
    motivo_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    notificacao_criada_em TIMESTAMPTZ,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(anuncio_perdido_id, anuncio_encontrado_id),
    CHECK (status IN ('pendente', 'notificado', 'aceito_usuario', 'descartado_usuario', 'confirmado', 'descartado_sistema'))
);

ALTER TABLE matches_animais
    ALTER COLUMN score_total TYPE NUMERIC(5,2)
    USING ROUND(score_total::numeric, 2),
    ALTER COLUMN score_visual TYPE NUMERIC(5,2)
    USING ROUND(score_visual::numeric, 2),
    ALTER COLUMN score_descricao TYPE NUMERIC(5,2)
    USING ROUND(score_descricao::numeric, 2),
    ALTER COLUMN score_localizacao TYPE NUMERIC(5,2)
    USING ROUND(score_localizacao::numeric, 2),
    ALTER COLUMN score_tempo TYPE NUMERIC(5,2)
    USING ROUND(score_tempo::numeric, 2);

DROP INDEX IF EXISTS conversas_participantes_animal_unique;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_indexes
        WHERE schemaname = 'public'
          AND indexname = 'conversas_participantes_unique'
    ) THEN
        CREATE UNIQUE INDEX conversas_participantes_unique
            ON conversas (usuario_1_id, usuario_2_id);
    END IF;
END
$$;

COMMIT;
